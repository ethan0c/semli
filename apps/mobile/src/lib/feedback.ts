import { createAudioPlayer, setAudioModeAsync, type AudioPlayer } from 'expo-audio';
import * as Haptics from 'expo-haptics';

import { useStore } from '@/store';
import { reportError } from './errors';

/**
 * What just happened, in UI terms. Each cue pairs a haptic with an optional sound.
 * Taps and selection changes are haptic-only so the app never chatters; sounds mark outcomes.
 */
export type Cue = 'tap' | 'select' | 'complete' | 'uncomplete' | 'ready' | 'success' | 'remove' | 'undo' | 'warning' | 'error';

type Sound = 'complete' | 'uncomplete' | 'ready' | 'success' | 'remove' | 'undo' | 'warning' | 'error';

// Generated by design/sounds.mjs.
const SOURCES: Record<Sound, number> = {
  complete: require('../../assets/sounds/complete.wav'),
  uncomplete: require('../../assets/sounds/uncomplete.wav'),
  ready: require('../../assets/sounds/ready.wav'),
  success: require('../../assets/sounds/success.wav'),
  remove: require('../../assets/sounds/remove.wav'),
  undo: require('../../assets/sounds/undo.wav'),
  warning: require('../../assets/sounds/warning.wav'),
  error: require('../../assets/sounds/error.wav'),
};

const CUES: Record<Cue, { haptic: () => Promise<void>; sound?: Sound }> = {
  tap: { haptic: () => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light) },
  select: { haptic: () => Haptics.selectionAsync() },
  complete: { haptic: () => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Medium), sound: 'complete' },
  uncomplete: { haptic: () => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Soft), sound: 'uncomplete' },
  ready: { haptic: () => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Medium), sound: 'ready' },
  success: { haptic: () => Haptics.notificationAsync(Haptics.NotificationFeedbackType.Success), sound: 'success' },
  remove: { haptic: () => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Rigid), sound: 'remove' },
  undo: { haptic: () => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Soft), sound: 'undo' },
  warning: { haptic: () => Haptics.notificationAsync(Haptics.NotificationFeedbackType.Warning), sound: 'warning' },
  error: { haptic: () => Haptics.notificationAsync(Haptics.NotificationFeedbackType.Error), sound: 'error' },
};

// UI sounds mix under the user's music and respect the ring/silent switch.
let players: Partial<Record<Sound, AudioPlayer>> | null = null;
function player(name: Sound): AudioPlayer {
  if (!players) {
    players = {};
    setAudioModeAsync({ playsInSilentMode: false, interruptionMode: 'mixWithOthers' }).catch((error: unknown) => reportError('feedback.audio_mode', error));
  }
  return (players[name] ??= Object.assign(createAudioPlayer(SOURCES[name]), { volume: 0.6 }));
}

/**
 * Loads every sound once the plan is ready. A player made on first use was still loading when
 * play() ran, so the first chime of each kind was silent, and most kinds are rare enough that
 * people heard almost none. Sounds still follow the ring/silent switch, as Apple asks of app sounds.
 */
export function preloadSounds() {
  if (!useStore.getState().settings.sounds) return;
  try {
    (Object.keys(SOURCES) as Sound[]).forEach((name) => player(name));
  } catch (error) {
    reportError('feedback.audio_preload', error);
  }
}

/** Play a cue, honoring the Sounds and Haptics switches in You → Preferences. */
export function feedback(cue: Cue) {
  const { sounds, haptics } = useStore.getState().settings;
  const { haptic, sound } = CUES[cue];
  if (haptics) haptic().catch((error: unknown) => reportError('feedback.haptics', error));
  if (sounds && sound) {
    try {
      const p = player(sound);
      void p.seekTo(0).catch((error: unknown) => reportError('feedback.audio_seek', error));
      p.play();
    } catch (error) {
      reportError('feedback.audio_play', error);
      // A missing audio route should never break the action that triggered it.
    }
  }
}
